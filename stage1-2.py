df["Future_Return"] = (
    df.groupby("Commodity")["Price"].shift(-1)
    / df["Price"]
    - 1
)

threshold = 0.002   # 0.2 %

df["Target"] = np.where(
    df["Future_Return"] > threshold, 1,
    np.where(
        df["Future_Return"] < -threshold, -1, 0
    )
)

df[["Date", "Commodity", "Price", "Future_Return", "Target"]].tail()

features = [
    "Price",
    "Volume",
    "Volatility_30d",
    "Momentum_12d",
    "RSI_14",
    "MACD",
    "Carry",
    "Roll_Yield",
    "Term_Spread",
    "ZScore_20"
]

data = df.dropna(
    subset=features + ["Future_Return"]
).copy()

print(data.shape)

dates_unique = sorted(data["Date"].unique())

cutoff = dates_unique[int(len(dates_unique) * 0.8)]

train = data[data["Date"] < cutoff].copy()
test = data[data["Date"] >= cutoff].copy()

X_train = train[features]
y_train = train["Target"]

X_test = test[features]
y_test = test["Target"]

print("Train :", X_train.shape)
