df["S_Momentum"] = np.where(
    df["Momentum_12d"] > 0, 1,
    np.where(df["Momentum_12d"] < 0, -1, 0)
)

# MACD
df["S_MACD"] = np.where(
    df["MACD"] > df["MACD_Signal"], 1,
    np.where(df["MACD"] < df["MACD_Signal"], -1, 0)
)

# Carry
df["S_Carry"] = np.where(
    df["Carry"] > 0, 1,
    np.where(df["Carry"] < 0, -1, 0)
)

df["Score"] = (
    df["S_RSI"]
    + df["S_Momentum"]
    + df["S_MACD"]
    + df["S_Carry"]
)

